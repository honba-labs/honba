//! Rendering the endpoint registry into a typed TypeScript fetch client.
//!
//! The client is generated from the same [`ENDPOINTS`] registry that produces
//! the OpenAPI `paths`, so a route cannot appear in one and not the other. Its
//! request and response types are imported from the sibling `domain.ts`
//! artifact, which is why the two must be regenerated together (`make codegen`).
//!
//! Output is deterministic: endpoints are sorted by path then method, and the
//! imported type names are emitted in sorted order.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use honba_messages::ENDPOINTS;

use crate::endpoints::{is_stream, operation_id, path_params, request_type_for, response_type_for};

/// The module specifier the generated client imports the domain types from.
///
/// `client.ts` is written to `src/core/api/generated/` and `domain.ts` to
/// `src/core/types/generated/`, so the import is a relative walk up to the
/// shared `core/` level (see `FRONTEND_CLIENT_DIR` / `FRONTEND_TS_DIR`).
const DOMAIN_IMPORT: &str = "../../types/generated/domain";

/// Renders the whole endpoint registry as a typed fetch client module.
pub fn render() -> String {
    let mut endpoints: Vec<(&'static str, &'static str)> = ENDPOINTS.to_vec();
    endpoints.sort_by(|a, b| a.1.cmp(b.1).then_with(|| a.0.cmp(b.0)));

    let mut out = String::new();
    out.push_str("// Generated by honba-codegen from the Rust endpoint registry.\n");
    out.push_str("// DO NOT EDIT: regenerate with `make client` instead.\n\n");

    out.push_str(&import_block(&endpoints));

    out.push_str(
        r#"export type ClientMethod = 'GET' | 'POST' | 'PUT' | 'DELETE';

export class HonbaApiError extends Error {
  readonly status: number;
  readonly body: unknown;

  constructor(status: number, message: string, body?: unknown) {
    super(message);
    this.name = 'HonbaApiError';
    this.status = status;
    this.body = body;
  }
}

export interface RequestOptions {
  body?: unknown;
  signal?: AbortSignal;
  headers?: Record<string, string>;
}

export function apiUrl(baseUrl: string, path: string, query?: object): string {
  const origin = typeof location !== 'undefined' ? location.origin : 'http://localhost';
  const url = new URL(`${baseUrl.replace(/\/$/, '')}${path}`, origin);
  if (query) {
    for (const [key, value] of Object.entries(query)) {
      if (value !== undefined && value !== null) {
        url.searchParams.set(key, String(value));
      }
    }
  }
  return url.toString();
}

export async function request<T>(
  fetchImpl: typeof fetch,
  method: ClientMethod,
  url: string,
  options: RequestOptions = {},
): Promise<ResponseEnvelope<T>> {
  const headers: Record<string, string> = { Accept: 'application/json', ...options.headers };
  let payload: string | undefined;
  if (options.body !== undefined) {
    headers['Content-Type'] = 'application/json';
    payload = JSON.stringify(options.body);
  }
  const response = await fetchImpl(url, { method, headers, body: payload, signal: options.signal });
  if (!response.ok) {
    let detail: unknown;
    try {
      detail = await response.json();
    } catch {
      detail = undefined;
    }
    throw new HonbaApiError(response.status, `${method} ${url} failed with ${response.status}`, detail);
  }
  return (await response.json()) as ResponseEnvelope<T>;
}

"#,
    );

    out.push_str(&stream_helper(&endpoints));
    out.push_str(&class_block(&endpoints));
    out
}

/// The `import type { ... } from '<domain>'` block, sorted and deduplicated.
fn import_block(endpoints: &[(&'static str, &'static str)]) -> String {
    let mut imports: BTreeSet<&str> = BTreeSet::new();
    imports.insert("ResponseEnvelope");
    if endpoints.iter().any(|(m, p)| is_stream(m, p)) {
        imports.insert("StreamFrame");
    }
    for (method, path) in endpoints {
        if let Some(resp) = response_type_for(method, path) {
            imports.insert(resp);
        }
        if let Some(req) = request_type_for(method, path) {
            imports.insert(req);
        }
    }

    let mut block = String::from("import type {\n");
    for name in &imports {
        writeln!(block, "  {name},").ok();
    }
    writeln!(block, "}} from '{DOMAIN_IMPORT}';\n").ok();
    block
}

/// The `HonbaClient` class with one method per registry endpoint.
fn class_block(endpoints: &[(&'static str, &'static str)]) -> String {
    let mut out = String::from(
        "export interface HonbaClientOptions {\n\
         \x20 baseUrl?: string;\n\
         \x20 fetch?: typeof fetch;\n\
         }\n\n\
         export class HonbaClient {\n\
         \x20 readonly baseUrl: string;\n\
         \x20 private readonly fetchImpl: typeof fetch;\n\n\
         \x20 constructor(options: HonbaClientOptions = {}) {\n\
         \x20   this.baseUrl = options.baseUrl ?? '/api/v1';\n\
         \x20   this.fetchImpl = options.fetch ?? globalThis.fetch;\n\
         \x20 }\n",
    );

    for (method, path) in endpoints {
        if is_stream(method, path) {
            out.push_str(&stream_method(method, path));
        } else {
            out.push_str(&request_method(method, path));
        }
    }

    out.push_str("}\n");
    out
}

/// One `async` method returning `Promise<ResponseEnvelope<T>>`.
fn request_method(method: &str, path: &str) -> String {
    let name = camelize(&operation_id(method, path));
    let params = path_params(path);
    let response = response_type_for(method, path).unwrap_or("Capabilities");
    let request = request_type_for(method, path);
    let is_query = method == "GET";
    let js_path = js_path(path, &params);

    let mut args: Vec<String> = params.iter().map(|p| format!("{p}: string")).collect();
    if is_query {
        if let Some(query) = request {
            args.push(format!("query?: {query}"));
        }
    } else if let Some(body) = request {
        args.push(format!("body: {body}"));
    }
    args.push("signal?: AbortSignal".to_string());

    let url_expr = if is_query && request.is_some() {
        format!("apiUrl(this.baseUrl, {js_path}, query)")
    } else {
        format!("apiUrl(this.baseUrl, {js_path})")
    };
    let body_field = if !is_query && request.is_some() {
        "body, "
    } else {
        ""
    };

    format!(
        "\n  async {name}({args}): Promise<ResponseEnvelope<{response}>> {{\n\
         \x20   return request<{response}>(this.fetchImpl, '{method}', {url_expr}, {{ {body_field}signal }});\n\
         \x20 }}\n",
        args = args.join(", "),
    )
}

/// The class method for the single SSE endpoint; delegates to the module helper.
fn stream_method(method: &str, path: &str) -> String {
    let _ = method;
    let name = STREAM_HELPER;
    let params = path_params(path);
    let query = request_type_for("GET", path);

    let mut args: Vec<String> = params.iter().map(|p| format!("{p}: string")).collect();
    if let Some(query) = query {
        args.push(format!("query?: {query}"));
    }
    args.push("signal?: AbortSignal".to_string());

    let mut call_args: Vec<String> = params.iter().map(|p| (*p).to_string()).collect();
    if query.is_some() {
        call_args.push("query".to_string());
    }
    call_args.push("signal".to_string());

    format!(
        "\n  {name}({args}): AsyncGenerator<StreamFrame, void, unknown> {{\n\
         \x20   return {name}(this.fetchImpl, this.baseUrl, {call_args});\n\
         \x20 }}\n",
        args = args.join(", "),
        call_args = call_args.join(", "),
    )
}

/// The exported `streamBacktestEvents` SSE helper, or an empty string if the
/// registry has no streaming endpoint.
fn stream_helper(endpoints: &[(&'static str, &'static str)]) -> String {
    let Some((_, path)) = endpoints.iter().find(|(m, p)| is_stream(m, p)) else {
        return String::new();
    };
    let params = path_params(path);
    let query = request_type_for("GET", path);
    let js_path = js_path(path, &params);

    let mut args: Vec<String> = vec![
        "fetchImpl: typeof fetch".to_string(),
        "baseUrl: string".to_string(),
    ];
    args.extend(params.iter().map(|p| format!("{p}: string")));
    if let Some(query) = query {
        args.push(format!("query?: {query}"));
    }
    args.push("signal?: AbortSignal".to_string());

    let url_expr = if query.is_some() {
        format!("apiUrl(baseUrl, {js_path}, query)")
    } else {
        format!("apiUrl(baseUrl, {js_path})")
    };

    format!(
        "export async function* {name}(\n\
         \x20 {args},\n\
         ): AsyncGenerator<StreamFrame, void, unknown> {{\n\
         \x20 const url = {url_expr};\n\
         \x20 const response = await fetchImpl(url, {{ headers: {{ Accept: 'text/event-stream' }}, signal }});\n\
         \x20 if (!response.ok) {{\n\
         \x20   throw new HonbaApiError(response.status, `GET ${{url}} failed with ${{response.status}}`);\n\
         \x20 }}\n\
         \x20 if (!response.body) {{\n\
         \x20   throw new HonbaApiError(response.status, 'stream response has no body');\n\
         \x20 }}\n\
         \x20 const reader = response.body.getReader();\n\
         \x20 const decoder = new TextDecoder();\n\
         \x20 let buffer = '';\n\
         \x20 for (;;) {{\n\
         \x20   const {{ value, done }} = await reader.read();\n\
         \x20   if (done) break;\n\
         \x20   buffer += decoder.decode(value, {{ stream: true }});\n\
         \x20   let boundary = buffer.indexOf('\\n\\n');\n\
         \x20   while (boundary >= 0) {{\n\
         \x20     const event = buffer.slice(0, boundary);\n\
         \x20     buffer = buffer.slice(boundary + 2);\n\
         \x20     const data = event\n\
         \x20       .split('\\n')\n\
         \x20       .filter((line) => line.startsWith('data:'))\n\
         \x20       .map((line) => line.slice(5).trim())\n\
         \x20       .join('\\n');\n\
         \x20     if (data.length > 0) {{\n\
         \x20       yield JSON.parse(data) as StreamFrame;\n\
         \x20     }}\n\
         \x20     boundary = buffer.indexOf('\\n\\n');\n\
         \x20   }}\n\
         \x20 }}\n\
         }}\n\n",
        name = STREAM_HELPER,
        args = args.join(",\n  "),
    )
}

/// The one streaming helper's fixed name (the registry has a single SSE route).
const STREAM_HELPER: &str = "streamBacktestEvents";

/// Renders a path into a JS string or template literal with `encodeURIComponent`.
fn js_path(path: &str, params: &[&str]) -> String {
    if params.is_empty() {
        return format!("'{path}'");
    }
    let mut out = String::from("`");
    let mut rest = path;
    while let Some(start) = rest.find('{') {
        let after = &rest[start + 1..];
        match after.find('}') {
            Some(end) => {
                let name = &after[..end];
                out.push_str(&rest[..start]);
                out.push_str(&format!("${{encodeURIComponent({name})}}"));
                rest = &after[end + 1..];
            }
            None => break,
        }
    }
    out.push_str(rest);
    out.push('`');
    out
}

/// `get_instruments_by_id` -> `getInstrumentsById`.
fn camelize(snake: &str) -> String {
    let mut out = String::with_capacity(snake.len());
    for (i, part) in snake.split('_').enumerate() {
        if i == 0 {
            out.push_str(part);
        } else {
            let mut chars = part.chars();
            if let Some(first) = chars.next() {
                out.extend(first.to_uppercase());
                out.push_str(chars.as_str());
            }
        }
    }
    out
}
