class TestSuiteParity:
    def test_generated_strategy_passes_same_suite_as_handwritten(self) -> None:
        bars = make_bars()
        handwritten = verify_source(HANDWRITTEN, config=CONFIG, bars=bars)
        generated = verify_source(GENERATED, config=CONFIG, bars=bars)

        assert handwritten.ok is True, list(handwritten.findings)
        assert generated.ok is True, list(generated.findings)

        for report in (handwritten, generated):
            assert report.sandbox is not None
            assert report.sandbox.smoke is not None
            assert report.sandbox.look_ahead is not None
            assert report.sandbox.look_ahead["checked_prefixes"] == len(bars)
            assert report.sandbox.look_ahead["violations"] == []
            assert report.sandbox.smoke["intents"] >= 1

    def test_smoke_is_deterministic_across_runs(self) -> None:
        bars = make_bars()
        first = verify_source(GENERATED, config=CONFIG, bars=bars)
        second = verify_source(GENERATED, config=CONFIG, bars=bars)
        assert first.ok and second.ok
        assert first.sandbox is not None and second.sandbox is not None
        assert first.sandbox.smoke == second.sandbox.smoke

    def test_verify_strategy_file_reads_source_and_config(self, tmp_path: Path) -> None:
        (tmp_path / "strategy.py").write_text(HANDWRITTEN, encoding="utf-8")
        (tmp_path / "config.toml").write_text(
            'name = "down_bar_buyer"\nsymbol = "NIFTY"\nexchange = "NSE"\n', encoding="utf-8"
        )
        report = verify_strategy_file(tmp_path / "strategy.py", bars=make_bars())
        assert report.ok is True, list(report.findings)

    def test_missing_strategy_class_is_reported(self) -> None:
        bars = make_bars()
        report = verify_source("x = 1\n", config=CONFIG, bars=bars)
        assert report.ok is False
        assert [f.code for f in report.findings] == [FindingCode.NO_STRATEGY]

    def test_multiple_strategy_classes_are_reported(self) -> None:
        source = (
            "from honba.strategies.base import Strategy\n"
            "class A(Strategy):\n    name = 'a'\n"
            "class B(Strategy):\n    name = 'b'\n"
        )
        report = verify_source(source, config=CONFIG, bars=make_bars())
        assert report.ok is False
        assert [f.code for f in report.findings] == [FindingCode.MULTIPLE_STRATEGIES]


class TestLookAhead:
    def test_peeking_strategy_has_no_violations_for_a_causal_builder(self) -> None:
        bars = make_bars()

        def build(data: list[Bar]) -> object:
            from honba.strategies.base import Strategy

            class Causal(Strategy):
                name = "causal"

                def on_bar(self, bar: Bar) -> None:
                    if bar.close < bar.open and not self.busy(bar.instrument_id):
                        self.buy(bar.instrument_id, 1.0)

            return Causal(config=CONFIG)

        report = check_look_ahead(build, bars)
        assert report.ok is True
        assert report.checked_prefixes == len(bars)

    def test_truncation_detects_a_peeking_strategy(self) -> None:
        bars = make_bars()
        namespace: dict[str, object] = {}
        exec(PEEKING, namespace)  # noqa: S102 - trusted red-team fixture under test
        build = namespace["build_strategy"]
        report = check_look_ahead(build, bars)
        assert report.ok is False
        assert report.violations
        assert report.violations[0].prefix_len >= 1

    def test_verify_source_reports_peeking_strategy(self) -> None:
        report = verify_source(PEEKING, config=CONFIG, bars=make_bars())
        assert report.ok is False
        assert FindingCode.LOOK_AHEAD in {f.code for f in report.findings}


class TestRedTeam:
    def test_forbidden_import_is_refused_before_execution(self) -> None:
        report = verify_source(FORBIDDEN_IMPORT, config=CONFIG, bars=make_bars())
        assert report.ok is False
        assert report.sandbox is None
        assert report.static[0].code == FindingCode.FORBIDDEN_IMPORT

    def test_runtime_network_attempt_is_blocked(self) -> None:
        outcome = run_in_sandbox(
            NETWORK_ATTEMPT,
            filename="<net>",
            config=CONFIG,
            bars=make_bars(),
            limits=SandboxLimits(cpu_seconds=5),
            timeout_s=30.0,
            check_look_ahead=False,
        )
        assert outcome.ok is False
        assert FindingCode.SANDBOX_DENIED in {f.code for f in outcome.findings}

    def test_runtime_process_spawn_is_blocked(self) -> None:
        outcome = run_in_sandbox(
            PROCESS_ATTEMPT,
            filename="<spawn>",
            config=CONFIG,
            bars=make_bars(),
            limits=SandboxLimits(cpu_seconds=5),
            timeout_s=30.0,
            check_look_ahead=False,
        )
        assert outcome.ok is False
        assert FindingCode.SANDBOX_DENIED in {f.code for f in outcome.findings}

    def test_runtime_file_write_is_blocked(self) -> None:
        outcome = run_in_sandbox(
            WRITE_ATTEMPT,
            filename="<writer>",
            config=CONFIG,
            bars=make_bars(),
            limits=SandboxLimits(cpu_seconds=5),
            timeout_s=30.0,
            check_look_ahead=False,
        )
        assert outcome.ok is False
        assert FindingCode.SANDBOX_DENIED in {f.code for f in outcome.findings}

    def test_child_cannot_forge_the_verdict(self) -> None:
        outcome = run_in_sandbox(
            FORGED_VERDICT,
            filename="<forger>",
            config=CONFIG,
            bars=make_bars(),
            limits=SandboxLimits(cpu_seconds=5),
            timeout_s=30.0,
            check_look_ahead=False,
        )
        assert outcome.ok is False
        assert FindingCode.SMOKE_FAILED in {f.code for f in outcome.findings}
        assert RESULT_PREFIX in outcome.stdout

    def test_forbidden_import_short_circuits_before_running(self) -> None:
        source = "import honba.strategies.loader as L\nL.sys.stdout.write('forged')\n"
        report = verify_source(source, config=CONFIG, bars=make_bars())
        assert report.ok is False
        assert report.sandbox is None
        assert report.static[0].code == FindingCode.FORBIDDEN_IMPORT

    def test_infinite_loop_is_killed_by_cpu_limit(self) -> None:
        outcome = run_in_sandbox(
            INFINITE_LOOP,
            filename="<spin>",
            config=CONFIG,
            bars=make_bars(),
            limits=SandboxLimits(cpu_seconds=1),
            timeout_s=30.0,
            check_look_ahead=False,
        )
        assert outcome.ok is False
        assert {f.code for f in outcome.findings} & {
            FindingCode.SANDBOX_LIMIT,
            FindingCode.SANDBOX_TIMEOUT,
        }

    @pytest.mark.skipif(
        sys.platform != "linux", reason="RLIMIT_AS baseline reads Linux /proc/self/status"
    )
    def test_memory_bomb_hits_address_space_limit(self) -> None:
        outcome = run_in_sandbox(
            MEMORY_BOMB,
            filename="<hogg>",
            config=CONFIG,
            bars=make_bars(),
            limits=SandboxLimits(cpu_seconds=10, address_space_mb=256),
            timeout_s=30.0,
            check_look_ahead=False,
        )
        assert outcome.ok is False
        assert FindingCode.SANDBOX_LIMIT in {f.code for f in outcome.findings}

    def test_nondeterministic_strategy_is_rejected(self) -> None:
        outcome = run_in_sandbox(
            NONDETERMINISTIC,
            filename="<coin>",
            config=CONFIG,
            bars=make_bars(),
            limits=SandboxLimits(cpu_seconds=10),
            timeout_s=30.0,
            check_look_ahead=False,
        )
        assert outcome.ok is False
        assert FindingCode.NONDETERMINISTIC in {f.code for f in outcome.findings}
