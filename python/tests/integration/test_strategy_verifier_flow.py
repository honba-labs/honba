"""Integration tests for the AI strategy verifier (E5-S5).

These exercise the real sandboxed subprocess: a clean synthetic strategy is built, run
deterministically and checked for look-ahead; the red-team corpus proves each guard fires. Every
test stays well inside its timeout because the sandbox is what bounds the untrusted run.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

from honba.ai.verification import (
    FindingCode,
    SandboxLimits,
    check_look_ahead,
    run_in_sandbox,
    verify_source,
    verify_strategy_file,
)
from honba.ai.verification.sandbox import RESULT_PREFIX
from honba.entities.bar import Bar
from honba.entities.instrument import InstrumentId
from honba.strategies.config import StrategyConfig

INSTRUMENT = InstrumentId("NIFTY", "NSE")
CLOSES = [
    100.0,
    101.0,
    103.0,
    106.0,
    104.0,
    101.0,
    98.0,
    96.0,
    99.0,
    102.0,
    105.0,
    107.0,
    104.0,
    100.0,
    97.0,
    95.0,
]


def make_bars(closes: list[float] | None = None) -> list[Bar]:
    series = CLOSES if closes is None else closes
    bars = []
    for i, close in enumerate(series):
        open_price = close - 0.5 if i % 2 == 0 else close + 0.5
        bars.append(
            Bar(
                INSTRUMENT,
                (i + 1) * 1_000_000_000,
                open_price,
                max(open_price, close) + 1.0,
                min(open_price, close) - 1.0,
                close,
                1_000.0,
            )
        )
    return bars


CONFIG = StrategyConfig(name="nifty", symbol="NIFTY", exchange="NSE")

HANDWRITTEN = """
from __future__ import annotations

from honba.entities.bar import Bar
from honba.strategies.base import Strategy


class DownBarBuyer(Strategy):
    name = "down_bar_buyer"

    def on_bar(self, bar: Bar) -> None:
        if bar.close < bar.open and not self.busy(bar.instrument_id):
            self.buy(bar.instrument_id, 1.0)
"""

# Something in the shape an LLM would emit: different names, comments, a helper, extra imports.
GENERATED = '''
# Generated by honba research loop. Verified before it is allowed to run.
from __future__ import annotations

import math

from honba.entities.bar import Bar
from honba.strategies.base import Parameter, Strategy


def _is_down_bar(bar: Bar) -> bool:
    """A red bar, guarded against float noise."""
    return math.isfinite(bar.close) and bar.close < bar.open


class GeneratedDownBar(Strategy):
    name = "generated_down_bar"
    threshold = Parameter(0.0, min=0.0, max=1.0, step=0.1)

    def on_bar(self, bar: Bar) -> None:
        if _is_down_bar(bar) and not self.busy(bar.instrument_id):
            self.buy(bar.instrument_id, 1.0)
'''

