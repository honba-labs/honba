PEEKING = """
from honba.entities.bar import Bar
from honba.strategies.base import Strategy


class Peeking(Strategy):
    name = "peeking"

    def __init__(self, config=None, closes=None) -> None:
        self._closes = list(closes or [])
        self._seen = 0

    def on_bar(self, bar: Bar) -> None:
        current = self._closes[self._seen]
        self._seen += 1
        if self._seen < len(self._closes):
            nxt = self._closes[self._seen]
            if nxt > current:
                self.buy(bar.instrument_id, 1.0)
            else:
                self.sell(bar.instrument_id, 1.0)


def build_strategy(bars):
    return Peeking(closes=[bar.close for bar in bars])
"""

