def run_mode_badge(
    mode: str, *, kill_switch: bool = False, approved: bool = True
) -> dict[str, Any]:
    """Describe a run mode for the ops console badge (E9-S6).

    ``live`` is blocked (``blocked`` True) unless the order is approved and the kill switch is
    off, so the console can never show a live badge for an unapproved intent.
    """
    if mode not in RUN_MODES:
        raise ValueError(f"unknown run mode {mode!r}; choose from {list(RUN_MODES)}")
    blocked = mode == "live" and (kill_switch or not approved)
    label = {"paper": "Paper", "signal_only": "Signal only", "live": "Live"}[mode]
    level = "live" if mode == "live" else ("warning" if mode == "signal_only" else "paper")
    return {
        "mode": mode,
        "label": label,
        "level": level,
        "blocked": blocked,
        "kill_switch": kill_switch,
    }


def trust_badges(validation: Mapping[str, Any] | None) -> list[dict[str, Any]]:
    """Turn a ``ValidationBlock`` into the result view's trust badges (DSR/PBO/holdout/...)."""
    if not validation:
        return []
    labels = {
        "dsr": "Deflated Sharpe",
        "pbo": "Prob. backtest overfitting",
        "holdout": "Hold-out",
        "walk_forward": "Walk-forward",
        "monte_carlo": "Monte Carlo",
        "cost_stress": "Cost stress",
    }
    badges: list[dict[str, Any]] = []
    for key, label in labels.items():
        block = validation.get(key)
        if not isinstance(block, Mapping):
            continue
        badges.append({"key": key, "label": label, "passed": bool(block.get("passed", False))})
    return badges


def drawdown_series(equity: Sequence[float]) -> list[float]:
    """Peak-to-trough drawdown (percent of the running peak) for each equity point."""
    out: list[float] = []
    peak = float("-inf")
    for value in equity:
        peak = max(peak, value)
        out.append(0.0 if peak <= 0 else (peak - value) / peak * 100.0)
    return out
