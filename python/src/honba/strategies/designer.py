RUN_MODES: tuple[str, ...] = ("paper", "signal_only", "live")
"""The run modes the ops console surfaces (E9-S6). ``live`` needs the kill switch honoured."""


@dataclass(frozen=True, slots=True)
class GraphIssue:
    """One verify finding, located by node id and/or generated-source line when known."""

    code: str
    message: str
    node_id: str | None = None
    lineno: int | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "message": self.message,
            "node_id": self.node_id,
            "lineno": self.lineno,
        }


@dataclass(frozen=True, slots=True)
class VerifyResult:
    """The outcome of verifying a graph: issues (empty when ok) and, on success, the IR."""

    ok: bool
    issues: tuple[GraphIssue, ...] = ()
    ir: dict[str, Any] | None = None
    manifest: StrategyManifest | None = None
    source: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "issues": [i.to_dict() for i in self.issues],
            "ir": self.ir,
        }


@dataclass
class DesignRun:
    """A run handle from the designer: the generated source and the backtest result."""

    handle: str
    graph_hash: str
    source: str
    result: Any = None  # honba.session.BacktestResult
    generated_filename: str = "strategy.py"


@dataclass(frozen=True, slots=True)
class VerifyRunResult:
    """Verify-then-run: always carries the verify outcome; ``run`` only when it succeeded."""

    verify: VerifyResult
    run: DesignRun | None = None


def verify_graph(graph: StrategyGraph, *, compile: bool = True) -> VerifyResult:
    """Validate ``graph`` and, when ``compile`` is set, compile it to the Rust IR.

    Graph defects are returned with the same codes as ``honba verify`` plus the originating
    node id and the generated-source line where the node is declared.
    """
    source = generate(graph)
    lines = graph_source_lines(source)

    def locate(node_id: str | None) -> int | None:
        return lines.get(node_id) if node_id else None

    try:
        graph.validate()
    except GraphError as exc:
        return VerifyResult(
            ok=False,
            issues=(GraphIssue(exc.code, exc.message, exc.node_id, locate(exc.node_id)),),
            source=source,
        )
    manifest = graph.to_manifest()
    if not compile:
        return VerifyResult(ok=True, ir=None, manifest=manifest, source=source)

    from honba.strategies.verify import VerifyError, verify_manifest

    try:
        ir = verify_manifest(manifest)
    except VerifyError as exc:
        return VerifyResult(
            ok=False,
            issues=(GraphIssue(exc.code, str(exc)),),
            manifest=manifest,
            source=source,
        )
    return VerifyResult(ok=True, ir=ir, manifest=manifest, source=source)


def verify_and_run(
    graph: StrategyGraph,
    *,
    bars: Sequence[Any],
    symbol: str,
    start: str,
    end: str,
    timeframe: str = "1d",
    exchange: str = "NSE",
    cash: float = 1_000_000.0,
    costs: str = "none",
    warmup_bars: int | None = None,
) -> VerifyRunResult:
    """Verify ``graph`` and, if it compiles, run the generated strategy over ``bars``.

    The run uses the existing :class:`honba.session.Honba` backtest (the event-driven runner
    and simulated execution port); nothing about the engine is reimplemented here. ``bars`` is
    an in-memory sequence of :class:`honba.entities.bar.Bar`. Returns a :class:`VerifyRunResult`
    whose ``run`` is ``None`` when verification fails.
    """
    verify = verify_graph(graph)
    if not verify.ok or verify.source is None:
        return VerifyRunResult(verify=verify)
    strategy_cls = compile_strategy_source(verify.source, graph.name)
    if strategy_cls is None:
        return VerifyRunResult(
            verify=VerifyResult(
                ok=False,
                issues=(GraphIssue("codegen_error", "generated source did not define a Strategy"),),
                source=verify.source,
            )
        )
    result = _run_strategy(
        strategy_cls,
        bars=bars,
        symbol=symbol,
        exchange=exchange,
        start=start,
        end=end,
        timeframe=timeframe,
        cash=cash,
        costs=costs,
        warmup_bars=warmup_bars if warmup_bars is not None else graph.warmup_bars,
    )
    run = DesignRun(
        handle=_run_handle(graph, start, end),
        graph_hash=graph.graph_hash(),
        source=verify.source,
        result=result,
    )
    return VerifyRunResult(verify=verify, run=run)


def compile_strategy_source(source: str, name: str) -> type | None:
    """Execute generated ``source`` and return its ``Strategy`` subclass (or ``None``)."""
    from honba.strategies.base import Strategy

    module: dict[str, Any] = {"__name__": f"honba_designer_{name}"}
    exec(compile(source, f"<designer:{name}>", "exec"), module)  # noqa: S102 - generated code
    for value in module.values():
        if isinstance(value, type) and issubclass(value, Strategy) and value is not Strategy:
            return value
    return None


def _run_strategy(
    strategy_cls: type,
    *,
    bars: Sequence[Any],
    symbol: str,
    exchange: str,
    start: str,
    end: str,
    timeframe: str,
    cash: float,
    costs: str,
    warmup_bars: int,
) -> Any:
    from honba.domain.instrument import InstrumentKind
    from honba.entities.instrument import Instrument
    from honba.session import Honba

    class _Provider:
        def bars(self, instrument_id, *, timeframe, start, end):
            return [b for b in bars if b.instrument_id == instrument_id]

        def instrument(self, instrument_id):
            return Instrument(instrument_id, InstrumentKind.EQUITY, 1.0, 0.05)

    return Honba.backtest(
        strategy_cls,
        symbol=symbol,
        exchange=exchange,
        start=start,
        end=end,
        timeframe=timeframe,
        cash=cash,
        costs=costs,
        data=_Provider(),
        warmup_bars=warmup_bars,
    ).run()


def _run_handle(graph: StrategyGraph, start: str, end: str) -> str:
    """A deterministic run handle (no wall clock): graph hash + window."""
    seed = f"{graph.graph_hash()}|{start}|{end}".encode()
    return "designer-" + hashlib.sha256(seed).hexdigest()[:24]


_NODE_LINE = re.compile(r"\.node\(id=[\"']([^\"']+)[\"']")


def graph_source_lines(source: str) -> dict[str, int]:
    """Map node id -> the 1-based line of its ``.node(id="...")`` call in generated source."""
    out: dict[str, int] = {}
    for lineno, line in enumerate(source.splitlines(), start=1):
        match = _NODE_LINE.search(line)
        if match:
            out.setdefault(match.group(1), lineno)
    return out


