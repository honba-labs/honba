"""AlgoDesigner control plane (E9-S4, ADR 0029): verify, run, publish, version, view.

This module is the Python API behind the AlgoDesigner's Verify / Run / Publish buttons and the
result views. It reuses the existing pieces rather than adding a second engine:

* verification is :func:`honba.strategies.verify.verify_manifest` (the Rust IR compiler);
* a run is :class:`honba.session.Honba` (the event-driven ``StrategyRunner`` + simulated
  execution port) driven with the strategy generated by
  :mod:`honba.strategies.graph_codegen`.

Everything here is data in, data out; the run helpers take an injected ``clock``/``seed`` and
never read the wall clock, so results are reproducible.

Also here are the pure helpers the ops console and result views share (mirrored in the
frontend): :func:`run_mode_badge`, :func:`trust_badges`, :func:`drawdown_series`.
"""

