@dataclass(frozen=True, slots=True)
class ChecklistItem:
    """One publish gate: a stable key, whether it passed, and a human detail."""

    key: str
    ok: bool
    detail: str = ""


def checklist_for_publish(
    graph: StrategyGraph,
    *,
    verify: VerifyResult | None = None,
    verification_ok: bool | None = None,
    run: DesignRun | None = None,
    validation: Mapping[str, Any] | None = None,
) -> tuple[ChecklistItem, ...]:
    """The publish-readiness checklist: what must hold before a graph can go live.

    ``verification_ok`` is the E5-S5 AI verifier's verdict; ``validation`` is a
    ``ValidationBlock`` (DSR/PBO/holdout/walk-forward) when a sweep has run.
    """
    items: list[ChecklistItem] = []
    try:
        graph.validate()
        graph_ok, graph_detail = True, ""
    except GraphError as exc:
        graph_ok, graph_detail = False, f"{exc.code}: {exc.message}"
    items.append(ChecklistItem("graph_valid", graph_ok, graph_detail))
    has_entry = any(n.type == "order" for n in graph.nodes)
    items.append(ChecklistItem("has_order", has_entry, "" if has_entry else "no order node"))
    if verify is not None:
        items.append(
            ChecklistItem(
                "compiles",
                verify.ok,
                "" if verify.ok else "; ".join(i.code for i in verify.issues),
            )
        )
    if verification_ok is not None:
        items.append(
            ChecklistItem(
                "ai_verified", verification_ok, "" if verification_ok else "verifier findings"
            )
        )
    if run is not None:
        result = run.result
        ran = result is not None and getattr(result, "fills", None) is not None
        items.append(ChecklistItem("backtested", bool(ran), ""))
    if validation is not None:
        passed = bool(validation.get("passed", False))
        items.append(ChecklistItem("validation_passed", passed, ""))
    return tuple(items)


