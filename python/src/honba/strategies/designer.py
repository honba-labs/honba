@dataclass(frozen=True, slots=True)
class GraphVersion:
    """A stored graph revision: its content hash and identity."""

    graph_hash: str
    schema_version: int
    name: str
    canonical_json: str


@dataclass(frozen=True, slots=True)
class GraphDiff:
    """The difference between two graph revisions (ids only, plus changed node ids)."""

    added_nodes: tuple[str, ...] = ()
    removed_nodes: tuple[str, ...] = ()
    changed_nodes: tuple[str, ...] = ()
    added_edges: tuple[str, ...] = ()
    removed_edges: tuple[str, ...] = ()

    @property
    def is_empty(self) -> bool:
        return not (
            self.added_nodes
            or self.removed_nodes
            or self.changed_nodes
            or self.added_edges
            or self.removed_edges
        )


def graph_version(graph: StrategyGraph) -> GraphVersion:
    """The current revision descriptor of ``graph`` (hash + canonical JSON for storage)."""
    return GraphVersion(
        graph_hash=graph.graph_hash(),
        schema_version=graph.schema_version,
        name=graph.name,
        canonical_json=graph.canonical_json(),
    )


def diff_graphs(base: StrategyGraph, other: StrategyGraph) -> GraphDiff:
    """Node/edge differences between ``base`` and ``other`` (node ids, and changed node ids)."""
    base_nodes = {n.id: n for n in base.nodes}
    other_nodes = {n.id: n for n in other.nodes}
    base_edges = {e.id: e for e in base.edges}
    other_edges = {e.id: e for e in other.edges}
    added_nodes = tuple(sorted(other_nodes.keys() - base_nodes.keys()))
    removed_nodes = tuple(sorted(base_nodes.keys() - other_nodes.keys()))
    changed_nodes = tuple(
        sorted(
            nid
            for nid in base_nodes.keys() & other_nodes.keys()
            if base_nodes[nid].model_dump() != other_nodes[nid].model_dump()
        )
    )
    added_edges = tuple(sorted(other_edges.keys() - base_edges.keys()))
    removed_edges = tuple(sorted(base_edges.keys() - other_edges.keys()))
    return GraphDiff(added_nodes, removed_nodes, changed_nodes, added_edges, removed_edges)


def restore_graph(version: GraphVersion | str) -> StrategyGraph:
    """Rebuild a graph from a stored :class:`GraphVersion` or its canonical JSON text."""
    from honba.strategies.graph import GRAPH_SCHEMA_VERSION

    text = version.canonical_json if isinstance(version, GraphVersion) else version
    import json as _json

    document = _json.loads(text)
    if document.get("schema_version") != GRAPH_SCHEMA_VERSION:
        raise GraphError(
            "unsupported_schema_version",
            f"cannot restore graph schema_version {document.get('schema_version')}",
        )
    return StrategyGraph.model_validate(document)


def persist_version(graph: StrategyGraph, directory: str | Path) -> Path:
    """Write ``graph``'s canonical JSON to ``<directory>/<graph_hash>.json`` and return the path."""
    from honba.strategies.graph import graph_hash

    root = Path(directory)
    root.mkdir(parents=True, exist_ok=True)
    digest = graph_hash(graph).split(":", 1)[1]
    path = root / f"{digest}.strategy.json"
    path.write_text(graph.canonical_json(), encoding="utf-8")
    return path


